def apply_descriptions(interface):
    for task in interface['task']:
        task['description'] = DESCRIPTIONS[task['name']]
        task['label'] = LABELS[task['name']]
    return interface


if __name__ == '__main__':
    path = Path(__file__).resolve().parents[1] / 'assets/interface.json'
    interface = apply_descriptions(json.loads(path.read_text(encoding='utf-8')))
